# Generates src/ui/UiFontData.h: 4-bit anti-aliased glyph atlases (Latin-1) from Inter.
import sys
from PIL import Image, ImageDraw, ImageFont
OUT = sys.argv[1]
FONTS = [  # (c name, file, pixel size)
    ("Small", "/usr/share/fonts/opentype/inter/Inter-Medium.otf", 18),
    ("Body",  "/usr/share/fonts/opentype/inter/Inter-Medium.otf", 24),
    ("Title", "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf", 34),
]
CHARS = list(range(32, 127)) + list(range(160, 256))
ATLAS_W = 512
out = []
out.append("// Generated by tools/genfont.py from the Inter typeface.\n"
           "// Inter is (c) The Inter Project Authors, licensed under the SIL Open Font\n"
           "// License 1.1 (https://openfontlicense.org). Do not edit by hand.\n"
           "#ifndef UI_FONT_DATA_H\n#define UI_FONT_DATA_H\n\n")
for name, path, size in FONTS:
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    x = y = 0; rowh = 0
    cells = []
    for c in CHARS:
        ch = chr(c)
        bbox = font.getbbox(ch)  # relative to origin at ascent baseline? (left, top, right, bottom) from top-left of text
        adv = font.getlength(ch)
        w = max(0, bbox[2] - bbox[0]); h = max(0, bbox[3] - bbox[1])
        if x + w + 1 > ATLAS_W:
            x = 0; y += rowh + 1; rowh = 0
        cells.append((c, x, y, w, h, bbox[0], bbox[1], int(round(adv))))
        x += w + 1; rowh = max(rowh, h)
    H = y + rowh + 1
    img = Image.new("L", (ATLAS_W, H), 0)
    d = ImageDraw.Draw(img)
    for (c, gx, gy, w, h, ox, oy, adv) in cells:
        if w and h:
            d.text((gx - ox, gy - oy), chr(c), font=font, fill=255)
    px = img.load()
    # pack 4bpp, two pixels per byte (high nibble first)
    data = bytearray()
    for yy in range(H):
        for xx in range(0, ATLAS_W, 2):
            a = (px[xx, yy] + 8) // 17; b = (px[xx + 1, yy] + 8) // 17
            data.append((min(a, 15) << 4) | min(b, 15))
    out.append("// %s: Inter %dpx, line height %d\n" % (name, size, ascent + descent))
    out.append("static const int kFont%sAscent = %d;\nstatic const int kFont%sLineHeight = %d;\n" % (name, ascent, name, ascent + descent + 4))
    out.append("static const int kFont%sAtlasW = %d;\nstatic const int kFont%sAtlasH = %d;\n" % (name, ATLAS_W, name, H))
    out.append("// {code, x, y, w, h, xoff, yoff(from top of line), advance}\n")
    out.append("static const short kFont%sGlyphs[][8] = {\n" % name)
    for (c, gx, gy, w, h, ox, oy, adv) in cells:
        out.append("  {%d,%d,%d,%d,%d,%d,%d,%d},\n" % (c, gx, gy, w, h, ox, oy, adv))
    out.append("};\n")
    out.append("static const unsigned char kFont%sAtlas[%d] = {\n" % (name, len(data)))
    for i in range(0, len(data), 24):
        out.append("  " + ",".join("0x%02x" % v for v in data[i:i+24]) + ",\n")
    out.append("};\n\n")
    img.save(OUT + "." + name + ".png")
out.append("#endif // UI_FONT_DATA_H\n")
open(OUT, "w", newline="\r\n").write("".join(out))
print("ok", OUT)
